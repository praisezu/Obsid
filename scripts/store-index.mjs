// Builds store/plugins.json from the plugin files in store/official/ and store/community/.
//   node scripts/store-index.mjs          rewrite the index
//   node scripts/store-index.mjs --check  fail if the index is out of date (used by CI)
// Each entry pins the sha256 of the file, so Vanta refuses a file that changed after review.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const out = join(root, "store/plugins.json");

function meta(code) {
    const block = code.match(/^\s*\/\*\*([\s\S]*?)\*\//);
    const m = {};
    if (block) for (const x of block[1].matchAll(/@(\w+)[ \t]+([^\r\n]+)/g)) m[x[1]] = x[2].trim();
    return m;
}

const plugins = [];
const problems = [];
for (const kind of ["official", "community"]) {
    const dir = join(root, "store", kind);
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).filter(f => f.endsWith(".js")).sort()) {
        const rel = `store/${kind}/${file}`;
        const code = readFileSync(join(dir, file), "utf8");
        if (code.includes("\r\n")) problems.push(`${rel}: use LF line endings`);
        const m = meta(code);
        for (const k of ["name", "description", "author", "version"]) if (!m[k]) problems.push(`${rel}: missing @${k} in the header comment`);
        if (!/(Vanta|Obsid)\s*\.\s*definePlugin\s*\(/.test(code)) problems.push(`${rel}: doesn't call Vanta.definePlugin(...)`);
        plugins.push({
            id: `${kind}/${file.replace(/\.js$/, "")}`,
            name: m.name ?? file,
            description: m.description ?? "",
            author: kind === "official" ? "Vanta" : (m.author ?? "Unknown"),
            version: m.version ?? "0.0.0",
            path: rel,
            sha256: createHash("sha256").update(code, "utf8").digest("hex"),
            tags: m.tags ? m.tags.split(",").map(s => s.trim()).filter(Boolean) : [],
        });
    }
}

const json = JSON.stringify({ about: "Generated by scripts/store-index.mjs. Don't edit by hand.", plugins }, null, 2) + "\n";
if (problems.length) { console.error("Store problems:\n  " + problems.join("\n  ")); process.exit(1); }
if (check) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== json) { console.error("store/plugins.json is out of date. Run: node scripts/store-index.mjs"); process.exit(1); }
    console.log(`store/plugins.json is up to date (${plugins.length} plugins)`);
} else {
    writeFileSync(out, json);
    console.log(`Wrote store/plugins.json (${plugins.length} plugins)`);
}
